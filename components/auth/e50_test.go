func TestTokenRevocation(t *testing.T) {
	_, h, ph := setupAuthWithExpiry(t, 24*time.Hour, 30*24*time.Hour)

	// Register
	regReq := httptest.NewRequest("POST", "/api/auth/register",
		strings.NewReader(`{"email":"revoke@test.com","password":"secret123"}`))
	regReq.Header.Set("Content-Type", "application/json")
	regW := httptest.NewRecorder()
	h.ServeHTTP(regW, regReq)
	if regW.Code != http.StatusCreated {
		t.Fatalf("register: %d", regW.Code)
	}
	var regResp map[string]any
	_ = json.NewDecoder(regW.Body).Decode(&regResp)
	rt, _ := regResp["refresh_token"].(string)
	at, _ := regResp["token"].(string)

	// logout-all
	laReq := httptest.NewRequest("POST", "/api/auth/logout-all", nil)
	laReq.Header.Set("Authorization", "Bearer "+at)
	laW := httptest.NewRecorder()
	ph.ServeHTTP(laW, laReq)
	if laW.Code != http.StatusOK {
		t.Fatalf("logout-all: expected 200, got %d: %s", laW.Code, laW.Body.String())
	}

	// Subsequent refresh with old token must fail
	rfReq := httptest.NewRequest("POST", "/api/auth/refresh",
		strings.NewReader(`{"refresh_token":"`+rt+`"}`))
	rfReq.Header.Set("Content-Type", "application/json")
	rfW := httptest.NewRecorder()
	h.ServeHTTP(rfW, rfReq)
	if rfW.Code != http.StatusUnauthorized {
		t.Fatalf("refresh after logout-all: expected 401, got %d: %s", rfW.Code, rfW.Body.String())
	}
}

func TestLogoutAllMultipleTokens(t *testing.T) {
	_, h, ph := setupAuthWithExpiry(t, 24*time.Hour, 30*24*time.Hour)

	// Register
	regReq := httptest.NewRequest("POST", "/api/auth/register",
		strings.NewReader(`{"email":"multirevoke@test.com","password":"secret123"}`))
	regReq.Header.Set("Content-Type", "application/json")
	regW := httptest.NewRecorder()
	h.ServeHTTP(regW, regReq)
	var regResp map[string]any
	_ = json.NewDecoder(regW.Body).Decode(&regResp)
	at, _ := regResp["token"].(string)
	rt1, _ := regResp["refresh_token"].(string)

	// Login again to get second refresh token
	loginReq := httptest.NewRequest("POST", "/api/auth/login",
		strings.NewReader(`{"email":"multirevoke@test.com","password":"secret123"}`))
	loginReq.Header.Set("Content-Type", "application/json")
	loginW := httptest.NewRecorder()
	h.ServeHTTP(loginW, loginReq)
	var loginResp map[string]any
	_ = json.NewDecoder(loginW.Body).Decode(&loginResp)
	rt2, _ := loginResp["refresh_token"].(string)

	// logout-all
	laReq := httptest.NewRequest("POST", "/api/auth/logout-all", nil)
	laReq.Header.Set("Authorization", "Bearer "+at)
	laW := httptest.NewRecorder()
	ph.ServeHTTP(laW, laReq)
	if laW.Code != http.StatusOK {
		t.Fatalf("logout-all: %d", laW.Code)
	}

	// Both refresh tokens must be invalidated
	for _, rt := range []string{rt1, rt2} {
		rfReq := httptest.NewRequest("POST", "/api/auth/refresh",
			strings.NewReader(`{"refresh_token":"`+rt+`"}`))
		rfReq.Header.Set("Content-Type", "application/json")
		rfW := httptest.NewRecorder()
		h.ServeHTTP(rfW, rfReq)
		if rfW.Code != http.StatusUnauthorized {
			t.Errorf("refresh %q after logout-all: expected 401, got %d", rt, rfW.Code)
		}
	}
}

