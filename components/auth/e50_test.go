// --- e50s02: Configurable token lifetimes ---

func setupAuthWithExpiry(t *testing.T, access, refresh time.Duration) (*auth.Auth, http.Handler, http.Handler) {
	t.Helper()
	logger := testLogger{}
	d := db.New(db.Options{Path: ":memory:", Logger: logger})
	a := auth.New(auth.Options{
		DB:            d,
		Logger:        logger,
		Secret:        "test-secret-32-chars!!!",
		AccessExpiry:  access,
		RefreshExpiry: refresh,
	})
	k := kernel.New(logger)
	k.Register(d)
	k.Register(a)
	if err := k.Start(); err != nil {
		t.Fatalf("start: %v", err)
	}
	t.Cleanup(func() { _ = k.Stop() })
	return a, a.Handler(), a.ProtectedHandler()
}

func TestTokenLifetimesDefault(t *testing.T) {
	_, h, _ := setupAuthWithExpiry(t, 0, 0) // zero → defaults
	regReq := httptest.NewRequest("POST", "/api/auth/register",
		strings.NewReader(`{"email":"defexpiry@test.com","password":"secret123"}`))
	regReq.Header.Set("Content-Type", "application/json")
	regW := httptest.NewRecorder()
	h.ServeHTTP(regW, regReq)
	if regW.Code != http.StatusCreated {
		t.Fatalf("register: expected 201, got %d", regW.Code)
	}
	var resp map[string]any
	if err := json.NewDecoder(regW.Body).Decode(&resp); err != nil {
		t.Fatalf("decode: %v", err)
	}
	expiresIn, ok := resp["expires_in"].(float64)
	if !ok {
		t.Fatalf("missing expires_in in response: %v", resp)
	}
	// Default is 24h = 86400s
	if int(expiresIn) != 86400 {
		t.Errorf("expected expires_in=86400, got %v", expiresIn)
	}
	expiresAt, ok := resp["expires_at"].(string)
	if !ok || expiresAt == "" {
		t.Fatalf("missing or empty expires_at in response: %v", resp)
	}
}

