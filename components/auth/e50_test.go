func TestTokenExpiryResponse(t *testing.T) {
	_, h, _ := setupAuthWithExpiry(t, 2*time.Hour, 30*24*time.Hour)
	regReq := httptest.NewRequest("POST", "/api/auth/register",
		strings.NewReader(`{"email":"expiryresp@test.com","password":"secret123"}`))
	regReq.Header.Set("Content-Type", "application/json")
	regW := httptest.NewRecorder()
	h.ServeHTTP(regW, regReq)
	if regW.Code != http.StatusCreated {
		t.Fatalf("register: expected 201, got %d", regW.Code)
	}
	var resp map[string]any
	if err := json.NewDecoder(regW.Body).Decode(&resp); err != nil {
		t.Fatalf("decode: %v", err)
	}

	// expires_in must be 7200 (2h)
	expiresIn, _ := resp["expires_in"].(float64)
	if int(expiresIn) != 7200 {
		t.Errorf("expected expires_in=7200, got %v", expiresIn)
	}

	// expires_at must be parseable RFC3339 and approximately 2h from now
	expiresAt, _ := resp["expires_at"].(string)
	parsed, err := time.Parse(time.RFC3339, expiresAt)
	if err != nil {
		t.Fatalf("invalid expires_at format %q: %v", expiresAt, err)
	}
	diff := time.Until(parsed)
	if diff < time.Hour || diff > 3*time.Hour {
		t.Errorf("expires_at not ~2h from now: diff=%v", diff)
	}
}

